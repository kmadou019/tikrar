// L'audio est découpé par sourate : un juz regroupe toutes les sourates qu'il touche, lues en entier.
export const MUSHAF_GROUPS: ChapterGroup[] = JUZ_STARTS.map(([startSurah], i) => {
  const next = JUZ_STARTS[i + 1];
  const last = !next ? 114 : next[1] === 1 ? next[0] - 1 : next[0];
  return {
    id: `juz-${i + 1}`,
    label: `Juz ${i + 1}`,
    chapters: Array.from({ length: last - startSurah + 1 }, (_, k) => startSurah + k),
  };
});
